#!/usr/bin/env bash
# ==============================================================================
# AnimeToon / Movie Stream Backend - 1-Click Domain & SSL Migration Script
# ==============================================================================
# Usage:
#   Interactive:  ./change_domain.sh
#   Direct:       ./change_domain.sh <frontend_domain> <backend_subdomain>
#   Example:      ./change_domain.sh animetoon.xyz api.animetoon.xyz
# ==============================================================================

set -e

DIR="$( cd "$( dirname "${BASH_SOURCE[0]}" )" && pwd )"
cd "$DIR"

GREEN='\033[0;32m'
CYAN='\033[0;36m'
YELLOW='\033[1;33m'
RED='\033[0;31m'
BOLD='\033[1m'
NC='\033[0m' # No Color

echo -e "${CYAN}==================================================================${NC}"
echo -e "${BOLD}${CYAN}🌐 AnimeToon Domain & SSL Change Automation Tool${NC}"
echo -e "${CYAN}==================================================================${NC}"

# Detect root / sudo
IS_ROOT=false
if [ "$EUID" -eq 0 ]; then
  IS_ROOT=true
fi

# Detect PORT from config.env (default 8000)
PORT=$(grep -E "^PORT" config.env 2>/dev/null | cut -d '=' -f2 | tr -d ' "' | tr -d "'" || echo "8000")
PORT=${PORT:-8000}

# Parse or prompt for domains
NEW_FRONTEND="$1"
NEW_BACKEND="$2"

if [ -z "$NEW_FRONTEND" ]; then
    echo -e "${YELLOW}Enter your NEW Frontend Domain (without https://, e.g. animetoon.xyz):${NC}"
    read -r -p "> " NEW_FRONTEND
fi

# Clean frontend domain
NEW_FRONTEND=$(echo "$NEW_FRONTEND" | sed -e 's|^https://||' -e 's|^http://||' -e 's|/$||' | tr -d ' ')

if [ -z "$NEW_BACKEND" ]; then
    echo -e "\n${YELLOW}Enter your NEW Backend Subdomain for API & Streaming (e.g. api.$NEW_FRONTEND):${NC}"
    read -r -p "> " NEW_BACKEND
    if [ -z "$NEW_BACKEND" ]; then
        NEW_BACKEND="api.$NEW_FRONTEND"
    fi
fi

# Clean backend domain
NEW_BACKEND=$(echo "$NEW_BACKEND" | sed -e 's|^https://||' -e 's|^http://||' -e 's|/$||' | tr -d ' ')

echo -e "\n${CYAN}──────────────────────────────────────────────────────────────────${NC}"
echo -e "🔹 ${BOLD}New Frontend Domain:${NC} ${GREEN}$NEW_FRONTEND${NC}"
echo -e "🔹 ${BOLD}New Backend Subdomain:${NC} ${GREEN}$NEW_BACKEND${NC}"
echo -e "🔹 ${BOLD}Backend Port:${NC}        ${GREEN}$PORT${NC}"
echo -e "${CYAN}──────────────────────────────────────────────────────────────────${NC}\n"

# 1. Update config.env
echo -e "${GREEN}[1/4] Updating configuration in config.env...${NC}"
if [ -f "config.env" ]; then
    # Update FRONTEND_LINK
    if grep -q "^FRONTEND_LINK" config.env; then
        sed -i -E "s|^FRONTEND_LINK[[:space:]]*=.*|FRONTEND_LINK = \"$NEW_FRONTEND\"|" config.env
    else
        echo "FRONTEND_LINK = \"$NEW_FRONTEND\"" >> config.env
    fi

    # Update BASE_URL if present
    if grep -q "^BASE_URL" config.env; then
        sed -i -E "s|^BASE_URL[[:space:]]*=.*|BASE_URL = \"https://$NEW_BACKEND\"|" config.env
    fi
    echo -e "✓ Successfully updated FRONTEND_LINK to: ${GREEN}$NEW_FRONTEND${NC}"
else
    echo -e "${RED}Error: config.env not found in $DIR!${NC}"
    exit 1
fi

# 2. Configure Reverse Proxy & SSL (Caddy or Nginx)
echo -e "\n${GREEN}[2/4] Configuring Web Server Reverse Proxy & SSL Certificate...${NC}"

SETUP_SSL_SUCCESS=false

# Method A: Caddy (Recommended)
if command -v caddy &> /dev/null; then
    echo -e "✓ Detected Caddy web server."
    CADDYFILE="/etc/caddy/Caddyfile"
    
    if [ "$IS_ROOT" = true ] || sudo -n true 2>/dev/null; then
        sudo mkdir -p /etc/caddy
        
        # Write clean Caddyfile with automatic HTTPS reverse proxy
        sudo bash -c "cat <<EOF > $CADDYFILE
# Auto-generated by AnimeToon change_domain.sh
$NEW_BACKEND {
    reverse_proxy localhost:$PORT {
        header_up Host {upstream_hostport}
        header_up X-Real-IP {remote_host}
        header_up X-Forwarded-For {remote_host}
        header_up X-Forwarded-Proto {scheme}
    }
}
EOF"
        echo -e "✓ Written Caddy configuration for: ${GREEN}$NEW_BACKEND${NC}"
        sudo systemctl reload caddy 2>/dev/null || sudo systemctl restart caddy 2>/dev/null || true
        SETUP_SSL_SUCCESS=true
        echo -e "✓ Caddy reloaded! Let's Encrypt / ZeroSSL automatic SSL is active."
    else
        echo -e "${YELLOW}Please run with sudo to update /etc/caddy/Caddyfile automatically.${NC}"
    fi

# Method B: Nginx
elif command -v nginx &> /dev/null; then
    echo -e "✓ Detected Nginx web server."
    NGINX_CONF="/etc/nginx/sites-available/movie-stream"
    
    if [ "$IS_ROOT" = true ] || sudo -n true 2>/dev/null; then
        sudo bash -c "cat <<EOF > $NGINX_CONF
server {
    listen 80;
    server_name $NEW_BACKEND;

    client_max_body_size 500M;

    location / {
        proxy_pass http://127.0.0.1:$PORT;
        proxy_http_version 1.1;
        proxy_set_header Upgrade \\\$http_upgrade;
        proxy_set_header Connection 'upgrade';
        proxy_set_header Host \\\$host;
        proxy_set_header X-Real-IP \\\$remote_addr;
        proxy_set_header X-Forwarded-For \\\$proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto \\\$scheme;
        proxy_cache_bypass \\\$http_upgrade;
    }
}
EOF"
        sudo ln -sf "$NGINX_CONF" /etc/nginx/sites-enabled/ 2>/dev/null || true
        sudo nginx -t && sudo systemctl reload nginx
        echo -e "✓ Nginx configured for: ${GREEN}$NEW_BACKEND${NC}"

        # Issue SSL via Certbot if installed
        if command -v certbot &> /dev/null; then
            echo -e "✓ Requesting SSL certificate via Certbot..."
            sudo certbot --nginx -d "$NEW_BACKEND" --non-interactive --agree-tos --register-unsafely-without-email --redirect 2>/dev/null || true
            SETUP_SSL_SUCCESS=true
        else
            echo -e "${YELLOW}Tip: Install certbot for 100% free automated SSL: sudo apt install -y certbot python3-certbot-nginx${NC}"
        fi
    fi
else
    echo -e "${YELLOW}Notice: Neither Caddy nor Nginx detected.${NC}"
    echo -e "If you are using Cloudflare Proxy (Orange Cloud), Cloudflare provides SSL automatically at the edge."
    echo -e "To install Caddy with auto-SSL in 1 command, run: ${CYAN}./setup_ssl.sh${NC}"
fi

# 3. Restart Backend Server
echo -e "\n${GREEN}[3/4] Restarting Movie Stream Backend Server...${NC}"
if systemctl is-active --quiet movie-stream.service 2>/dev/null; then
    echo -e "Restarting systemd service (movie-stream.service)..."
    if [ "$IS_ROOT" = true ]; then
        systemctl restart movie-stream.service
    else
        sudo systemctl restart movie-stream.service
    fi
    echo -e "✓ Service restarted successfully."
elif [ -f "./run.sh" ]; then
    echo -e "Restarting via ./run.sh..."
    bash ./run.sh
fi

# 4. Display Complete Step-by-Step Summary
echo -e "\n${GREEN}[4/4] VPS Domain update complete!${NC}"
echo -e "${CYAN}==================================================================${NC}"
echo -e "${BOLD}${GREEN}🎉 DOMAIN SWITCH COMPLETE ON VPS!${NC}"
echo -e "${CYAN}==================================================================${NC}"

echo -e "\n${BOLD}${YELLOW}📋 NEXT STEPS (Required in Cloudflare & Vercel):${NC}\n"

echo -e "${BOLD}1. Cloudflare DNS for ${CYAN}$NEW_FRONTEND${NC}:${NC}"
echo -e "   • Type: ${BOLD}A Record${NC}   | Name: ${BOLD}api${NC}  | IPv4: ${BOLD}(Your VPS IP)${NC} | Proxy: ${BOLD}Proxied (Orange Cloud) or DNS Only${NC}"
echo -e "   • Type: ${BOLD}CNAME${NC}      | Name: ${BOLD}@${NC}    | Target: ${BOLD}cname.vercel-dns.com${NC} | Proxy: ${BOLD}DNS Only (initially)${NC}"
echo -e "   • Type: ${BOLD}CNAME${NC}      | Name: ${BOLD}www${NC}  | Target: ${BOLD}cname.vercel-dns.com${NC} | Proxy: ${BOLD}DNS Only (initially)${NC}"

echo -e "\n${BOLD}2. Vercel Dashboard (Frontend):${NC}"
echo -e "   • Go to: ${CYAN}Vercel Dashboard → Project Settings → Domains${NC}"
echo -e "   • Add your new domain: ${GREEN}$NEW_FRONTEND${NC} and ${GREEN}www.$NEW_FRONTEND${NC}"
echo -e "   • Go to: ${CYAN}Project Settings → Environment Variables${NC}"
echo -e "   • Set ${BOLD}VITE_BASE_URL${NC} = ${GREEN}https://$NEW_BACKEND${NC}"
echo -e "   • Click ${BOLD}Redeploy${NC} (Deployments → Latest → Redeploy)"

echo -e "\n${BOLD}3. Redirect OLD Domain (e.g. animetoon.in) → NEW Domain (${GREEN}$NEW_FRONTEND${NC}):${NC}"
echo -e "   ${CYAN}Method A (Cloudflare - Recommended):${NC}"
echo -e "   1. Open Cloudflare dashboard for old domain (animetoon.in)"
echo -e "   2. Go to: ${BOLD}Rules → Redirect Rules → Create Rule${NC}"
echo -e "   3. Name: ${BOLD}Redirect to New Domain${NC}"
echo -e "   4. When: ${BOLD}All incoming requests${NC}"
echo -e "   5. Type: ${BOLD}Dynamic${NC}"
echo -e "   6. Expression: ${BOLD}concat(\"https://$NEW_FRONTEND\", http.request.uri.path)${NC}"
echo -e "   7. Status: ${BOLD}301 (Moved Permanently)${NC}"
echo -e "   8. Check: ${BOLD}Preserve query string${NC} → Click ${BOLD}Deploy${NC}!"
echo -e "   ${YELLOW}(All old URLs will instantly redirect to the new domain!)${NC}"

echo -e "\n${CYAN}==================================================================${NC}\n"
